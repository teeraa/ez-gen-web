/** Where the first [placeholder] is in a prompt, to select it after inserting a template. */
export function firstPlaceholder(prompt: string): [number, number] | null {
  const start = prompt.indexOf("[");
  const end = start < 0 ? -1 : prompt.indexOf("]", start);
  return start < 0 || end < 0 ? null : [start, end + 1];
}
